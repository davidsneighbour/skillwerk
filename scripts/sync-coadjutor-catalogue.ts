import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { collections } from "./collections.ts";

// Only indexed entry points belong to the published catalogue; ignore local drafts.
const paths = execFileSync(
  "git",
  ["ls-files", "-z", "--", "collections/*/skills/*/SKILL.md"],
  { encoding: "utf8" },
)
  .split("\0")
  .filter(Boolean)
  .sort();
const target = "collections/clerkwork/skills/coadjutor/resources/catalogue.md";
const routing: Record<string, string> = {
  apparatus: "No collection router; select web-screenshot directly.",
  clerkwork: "foreman; coadjutor handles discovery across collections.",
  fettle: "fettle",
  gallimaufry: "gallimaufry",
  gazetteer: "gazetteer",
  idiolect:
    "No collection router; idiolect handles personal writing profiles, checks, and rewrites directly.",
  patternbook:
    "patternbook is a placeholder, not an operating router; select a specialist directly.",
  posthaste: "posthaste",
};
const lines = [
  "# Skillwerk capability catalogue",
  "",
  "Generated from indexed skill entry points by `node scripts/sync-coadjutor-catalogue.ts`. Descriptions reflect source capabilities, not installation status. Do not edit this file by hand.",
];
for (const collection of collections) {
  lines.push(
    "",
    `## ${collection[0]?.toUpperCase()}${collection.slice(1)}`,
    "",
    `Collection entry point: ${routing[collection]}`,
    "",
  );
  for (const path of paths.filter((path) =>
    path.startsWith(`collections/${collection}/skills/`),
  )) {
    const source = readFileSync(path, "utf8");
    const frontmatter = /^---\r?\n([\s\S]*?)\r?\n---/.exec(source)?.[1] ?? "";
    const name = /^name:\s*(.+)$/m.exec(frontmatter)?.[1]?.trim();
    const match =
      /^description:[ \t]*(.*)(?:\r?\n((?:[ \t]+[^\r\n]*(?:\r?\n|$))*))?/m.exec(
        frontmatter,
      );
    const raw = match?.[1]?.trim() ?? "";
    const description = /^[>|][-+]?$/.test(raw)
      ? (match?.[2] ?? "").trim().replace(/\s+/g, " ")
      : raw.replace(/^(["'])(.*)\1$/, "$2");
    if (!name || !description) {
      lines.push(
        `* \`${path.split("/").at(-2)}\`: Unavailable; this entry point has no complete capability metadata.`,
      );
      continue;
    }
    lines.push(`* \`${name}\`: ${description}`);
  }
}
const output = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== output) {
    console.error(
      "Coadjutor catalogue is stale; run node scripts/sync-coadjutor-catalogue.ts",
    );
    process.exitCode = 1;
  } else console.log("Coadjutor catalogue is current.");
} else {
  writeFileSync(target, output);
  console.log(`Updated ${target}`);
}
